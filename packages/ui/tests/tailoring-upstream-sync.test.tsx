/** @vitest-environment jsdom */
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import '@testing-library/jest-dom/vitest';
import type { DraftEnvelope } from '@featherduster/core';
import { UpstreamSyncControl } from '../src/views/tailoring/UpstreamSyncDialog';
import { DraftCoordinator } from '../src/tailoring-drafts/coordinator';
import { BrowserRecovery } from '../src/tailoring-drafts/recovery';
import { apiClient } from '../src/api/client';
import { sseClient } from '../src/api/events';
import { TailoringRun } from '../src/views/tailoring/TailoringRun';
const id = '11111111-1111-4111-8111-111111111111', time = '2026-09-30T12:00:00Z';
const spec = { profile: { name: 'Person', email: 'a@b.com', title: 'Engineer' }, summary: 'Original', experiences: [], education: [], skills: [] };
const server: DraftEnvelope = { token: { revision: 1, fingerprint: 'one' }, record: { id, kind: 'manual', schemaVersion: 1, lifecycle: 'draft', revision: 1, createdAt: time, editedAt: time, savedAt: time, base: { resumeId: 'base', fingerprint: 'old', spec }, payload: { ...spec, summary: 'Local', experiences: [], jobDescription: '', selectedResumeId: 'base', squeezeMode: false }, appliedContent: {}, context: {} } };
let writer: DraftCoordinator, recovery: BrowserRecovery;
beforeEach(async () => {
  localStorage.clear(); recovery = new BrowserRecovery();
  writer = new DraftCoordinator({ draftId: id, workspaceId: 'workspace', recovery, api: { getHealth: vi.fn().mockResolvedValue({ workspaceId: 'workspace' }), saveTailoringDraft: vi.fn() } as any }); await writer.hydrate(server);
  vi.spyOn(apiClient, 'getDraftUpstream').mockResolvedValue({ fingerprint: 'new', record: server.record, changed: true, missing: false });
  vi.spyOn(apiClient, 'previewDraftSync').mockResolvedValue({ upstreamFingerprint: 'new', record: server.record, candidate: { ...spec, summary: 'Local' }, targetMap: {}, conflicts: [{ id: '/summary', path: '/summary', base: 'Original', local: 'Local', upstream: 'Upstream' }] });
});
afterEach(() => { cleanup(); writer.dispose(); recovery.dispose(); sseClient.resetForTesting(); vi.restoreAllMocks(); });
it('checks on open/focus and cancels preview without syncing', async () => {
  const sync = vi.spyOn(apiClient, 'syncTailoringDraft');
  render(<UpstreamSyncControl coordinator={writer} verifyWorkspace={async () => {}} />);
  expect(await screen.findByText('Base resume updated')).toBeInTheDocument();
  fireEvent(window, new Event('focus')); await waitFor(() => expect(apiClient.getDraftUpstream).toHaveBeenCalledTimes(2));
  expect(screen.getByRole('button', { name: 'Sync upstream' })).toHaveClass('rounded-desk', 'border');
  fireEvent.click(screen.getByRole('button', { name: 'Sync upstream' }));
  expect(await screen.findByRole('dialog', { name: 'Sync upstream resume' })).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Apply upstream sync' })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(sync).not.toHaveBeenCalled(); expect(writer.getSnapshot().record).toEqual(server.record);
});
it('requires per-conflict choices and reconciles only after acknowledgement', async () => {
  const result = { ...server, token: { revision: 2, fingerprint: 'two' }, record: { ...server.record, revision: 2 } };
  const sync = vi.spyOn(apiClient, 'syncTailoringDraft').mockResolvedValue(result);
  const verify = vi.fn().mockResolvedValue(undefined);
  render(<UpstreamSyncControl coordinator={writer} verifyWorkspace={verify} />);
  fireEvent.click(await screen.findByRole('button', { name: 'Sync upstream' }));
  await screen.findByRole('dialog'); fireEvent.click(screen.getByLabelText('Summary: use upstream'));
  const candidate = screen.getByText('Merged candidate preview').closest('details')!;
  expect(within(candidate).getByText('Upstream')).toBeInTheDocument();
  expect(within(candidate).queryByText('Local')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Apply upstream sync' }));
  await waitFor(() => expect(writer.getSnapshot().token).toEqual(result.token));
  expect(sync).toHaveBeenCalledWith(id, expect.objectContaining({ expected: server.token, upstreamFingerprint: 'new', resolutions: { '/summary': 'upstream' } }));
  expect(verify.mock.calls.length).toBeGreaterThanOrEqual(4);
});
it('shows missing source and disables sync while keeping the snapshot', async () => {
  vi.mocked(apiClient.getDraftUpstream).mockResolvedValue({ fingerprint: null, record: server.record, changed: false, missing: true });
  render(<UpstreamSyncControl coordinator={writer} verifyWorkspace={async () => {}} />);
  expect(await screen.findByText(/Live source unavailable/)).toBeInTheDocument(); expect(screen.getByRole('button', { name: 'Sync upstream' })).toBeDisabled();
  expect(writer.getSnapshot().record?.base?.spec).toEqual(spec);
});
it('retains newer edits received while preview is open instead of replacing them', async () => {
  const sync = vi.spyOn(apiClient, 'syncTailoringDraft');
  render(<UpstreamSyncControl coordinator={writer} verifyWorkspace={async () => {}} />);
  fireEvent.click(await screen.findByRole('button', { name: 'Sync upstream' })); await screen.findByRole('dialog');
  act(() => writer.edit({ ...server.record.payload, summary: 'Newer local text' } as any));
  fireEvent.click(screen.getByLabelText('Summary: keep local')); fireEvent.click(screen.getByRole('button', { name: 'Apply upstream sync' }));
  expect(await screen.findByRole('alert')).toHaveTextContent(/changed.*preview/i); expect(sync).not.toHaveBeenCalled();
  expect(writer.getSnapshot().record?.payload).toMatchObject({ summary: 'Newer local text' });
});
it('keeps a new recovery conflict that arrives during sync acknowledgement', async () => {
  let finish!: (value: DraftEnvelope) => void;
  vi.spyOn(apiClient, 'syncTailoringDraft').mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  render(<UpstreamSyncControl coordinator={writer} verifyWorkspace={async () => {}} />);
  fireEvent.click(await screen.findByRole('button', { name: 'Sync upstream' })); await screen.findByRole('dialog');
  fireEvent.click(screen.getByLabelText('Summary: keep local')); fireEvent.click(screen.getByRole('button', { name: 'Apply upstream sync' }));
  await waitFor(() => expect(finish).toBeDefined());
  await act(async () => { writer.enterConflict(Error('Another writer changed this draft')); finish({ ...server, token: { revision: 2, fingerprint: 'synced' } }); });
  expect(writer.getSnapshot().status).toBe('conflict'); expect(recovery.list('workspace').snapshots.length).toBeGreaterThan(0);
});
it('disables approval of an output with unresolved upstream review flags', async () => {
  const step = { status: 'done', completed_at: null, input_hash: null, error: null, raw_output: null };
  const manifest = { slug: 'run', draft_id: id, title: 'Review run', runner: 'fake', state: 'proposals_review', created: time, updated: time, base_resume: 'base', model: '', error: null, finalized_path: null, steps: { analysis: { ...step, status: 'approved' }, alignment: { ...step, status: 'approved' }, proposals: step, brief: { ...step, status: 'pending' } } } as any;
  const draft = { ...server, record: { ...server.record, kind: 'run', runSlug: 'run', payload: { proposals: { proposals: [] }, proposalTextById: {}, artifactTokens: {} }, appliedContent: { proposals: { proposals: [] } }, upstreamSync: { candidate: spec, previous: { posting: 'Posting', manifest, base: server.record.base }, previousAppliedContent: {}, reviewProposalIds: [], staleSteps: ['proposals', 'brief'] } } } as any;
  vi.spyOn(apiClient, 'getHealth').mockResolvedValue({ status: 'ok', workspaceId: 'workspace', workspaceDir: '/workspace' });
  vi.spyOn(apiClient, 'getEvidence').mockResolvedValue([]);
  vi.spyOn(apiClient, 'getTailoringRun').mockResolvedValue({ manifest, posting: 'Posting', draft, base_resume: spec, analysis: null, alignment: null, proposals: [], page_budget: null, resume: null, brief_markdown: null, alignment_summary: null });
  render(<TailoringRun slug="run" selectedStep="proposals" onBack={() => {}} onOpenInCanvas={() => {}} />);
  expect(await screen.findByRole('button', { name: /Approve.*brief/i })).toBeDisabled();
  expect(screen.getByRole('button', { name: 'Apply proposal edits' })).toBeEnabled();
  fireEvent.click(screen.getByText('Upstream sync comparison and review'));
  expect(screen.getByText('Previous analysis')).toBeInTheDocument();
  expect(screen.getByText('Previous alignment')).toBeInTheDocument();
  expect(screen.getByText('Previous proposals')).toBeInTheDocument();
  expect(screen.getByText('Previous interview brief')).toBeInTheDocument();
  expect(document.body.textContent).not.toContain('draft_id');
  expect(document.body.textContent).not.toContain('input_hash');
  expect(document.body.textContent).not.toContain('fingerprint');
});
it('renders array choices as resume sections and updates the candidate without writing on cancel', async () => {
  const experience = { company: 'Local company', role: 'Engineer', startDate: '2020', endDate: 'Present', bullets: [{ text: 'Local achievement' }] };
  const upstreamExperience = { ...experience, company: 'Upstream company', bullets: [{ text: 'Upstream achievement' }] };
  vi.mocked(apiClient.previewDraftSync).mockResolvedValue({ upstreamFingerprint: 'new', record: server.record, candidate: { ...spec, experiences: [experience] }, targetMap: {}, conflicts: [{ id: '/experiences', path: '/experiences', base: [], local: [experience], upstream: [upstreamExperience] }] });
  const sync = vi.spyOn(apiClient, 'syncTailoringDraft');
  render(<UpstreamSyncControl coordinator={writer} verifyWorkspace={async () => {}} />);
  fireEvent.click(await screen.findByRole('button', { name: 'Sync upstream' })); await screen.findByRole('dialog');
  const candidate = screen.getByText('Merged candidate preview').closest('details')!;
  expect(within(candidate).getByRole('heading', { name: 'Local company' })).toBeInTheDocument();
  fireEvent.click(screen.getByLabelText('Experiences: use upstream'));
  expect(within(candidate).getByRole('heading', { name: 'Upstream company' })).toBeInTheDocument();
  expect(within(candidate).getByText('Upstream achievement')).toBeInTheDocument();
  expect(within(candidate).queryByText('Local achievement')).not.toBeInTheDocument();
  expect(candidate.textContent).not.toContain('"bullets"');
  fireEvent.click(screen.getByLabelText('Experiences: keep local'));
  expect(within(candidate).getByRole('heading', { name: 'Local company' })).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(sync).not.toHaveBeenCalled(); expect(writer.getSnapshot().record).toEqual(server.record);
});
