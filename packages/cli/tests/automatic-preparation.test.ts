import { afterEach, expect, it, vi } from 'vitest';
import { automaticPreparationFixture } from './fixtures/automatic-preparation-fixture.js';
const cleanups: (() => Promise<void>)[] = [];
afterEach(async () => { for (const cleanup of cleanups.splice(0)) await cleanup(); });
const fixture = () => automaticPreparationFixture(cleanup => cleanups.push(cleanup));
it('schedules seven selected jobs, preserves selection order and replays without extra captures or calls', async () => {
  const f = fixture(), jobs = await Promise.all(Array.from({ length: 8 }, () => f.add()));
  const members = jobs.slice(0, 7).reverse().map(job => ({ job_id: job.id, expected_revision: job.revision }));
  expect(f.run).not.toHaveBeenCalled();
  const body = { members, idempotency_key: 'selected-seven' }, result = f.runtime().prepareBatch(body);
  expect(f.runtime().prepareBatch(body).replayed).toBe(true);
  await vi.waitFor(() => expect(f.runtime().readBatch(result.result.id).counts.ready).toBe(7), { timeout: 15000, interval: 100 });
  expect(f.runtime().readBatch(result.result.id).queue.map(q => q.job_id)).toEqual(members.map(m => m.job_id));
  expect(f.run).toHaveBeenCalledTimes(28);
  expect(f.runtime().repository.getJob(jobs[7].id).preparation_state).toBe('saved');
  const r = await f.reopen(); r.initialize();
  expect(r.readBatch(result.result.id).counts.ready).toBe(7);
  expect(r.prepareBatch(body).replayed).toBe(true);
  await new Promise(resolve => setTimeout(resolve, 300));
  expect(f.run).toHaveBeenCalledTimes(28);
  expect(r.repository.listEvents(jobs[0].id).some(e => e.payload.kind === 'resume_review')).toBe(false);
}, 20000);
it('retries one transient dispatch, exhausts a second failure technically, and honors durable Stop', async () => {
  const f = fixture(), job = await f.add();
  f.run.mockRejectedValue(new Error('temporarily offline'));
  const request = { members: [{ job_id: job.id, expected_revision: job.revision }], idempotency_key: 'failure' };
  const batch = f.runtime().prepareBatch(request).result;
  await vi.waitFor(() => expect(f.runtime().readBatch(batch.id).counts.technical).toBe(1), { timeout: 5000 });
  expect(f.run).toHaveBeenCalledTimes(2);
  expect(f.runtime().questions.read(batch.id)).toEqual([]);
  f.runtime().service.stopProcessing('stop');
  const current = f.runtime().repository.getJob(job.id);
  f.runtime().coordinator.retry(job.id, current.revision, 'explicit-retry');
  await new Promise(resolve => setTimeout(resolve, 350)); expect(f.run).toHaveBeenCalledTimes(2);
  expect(f.runtime().coordinator.retry(job.id, current.revision, 'explicit-retry').replayed).toBe(true);
});
it('enforces an explicitly configured automatic call ceiling before another model dispatch', async () => {
  const fs = await import('node:fs'), path = await import('node:path');
  const f = fixture(), job = await f.add(), r = f.runtime();
  fs.writeFileSync(path.join(f.root, '.featherduster/config.yaml'), 'automatic_preparation:\n  max_model_calls: 1\n  max_repair_attempts: 0\n');
  const request = { members: [{ job_id: job.id, expected_revision: job.revision }], idempotency_key: 'configured-ceiling' };
  const batch = r.prepareBatch(request).result;
  await vi.waitFor(() => expect(r.readBatch(batch.id).counts.technical).toBe(1), { timeout: 5000 });
  expect(f.run).toHaveBeenCalledTimes(1);
  const member = r.batches.members(batch.id)[0];
  expect(r.repository.getInputSnapshot(member.input_snapshot_id).policy.max_model_calls).toBe(1);
  expect(r.batches.cycle(member.cycle_id).usage.calls).toBe(1);
  expect(r.repository.getJob(job.id).artifact_version_ids).toEqual([]);
  expect(r.questions.read(batch.id)).toEqual([]);
  expect(r.prepareBatch(request).replayed).toBe(true);
  expect(f.run).toHaveBeenCalledTimes(1);
});
